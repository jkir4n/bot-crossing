/**
 * OpenCode adapter (fork addition).
 *
 * Three sources, merged per scan — the full history is the point, because
 * Desktop's serve API only shows the sessions loaded in the RUNNING Desktop
 * instance (2 at last check) while the real history (25+ sessions across
 * ~10 projects) lives in the session store on the WinPC:
 *
 *   1. Remote session-store snapshot (PRIMARY). The store
 *      (`opencode.db`, the SQLite DB with `session` / `project` /
 *      `workspace` / `session_input` / `part` tables) lives on the WinPC;
 *      the colony pulls a copy over SSH into a local snapshot dir and
 *      queries the copy, never the live file (live-querying over a network
 *      share risks WAL corruption, and a copy never locks Desktop's files).
 *      The pull is mtime-gated — a cheap `ssh` stat runs at most once per
 *      STAT_TTL window, and the ~500MB bulk copy runs only when the remote
 *      signature actually changed, at most once per PULL_MIN window, in the
 *      background so a scan never blocks on a transfer. While Desktop runs,
 *      its `-wal` carries the newest writes, so db AND wal are pulled; the
 *      `-shm` is deliberately NOT copied (shared-memory, rebuilt on open —
 *      a live shm copy is meaningless). The wal stages beside the pending db
 *      under its real `-wal` name, so verification opens the same pair the
 *      swap would publish; a mid-pull Desktop write (fresh re-stat drifts
 *      from the pre-pull signature) or a failed verify discards the set and
 *      the previous snapshot keeps serving.
 *      Config: OPENCODE_DB_SSH_TARGET (falls back to OPENCODE_SSH_TARGET,
 *      the same target the tunnel keeper uses), OPENCODE_DB_REMOTE_PATH
 *      (default `.local/share/opencode/opencode.db`, forward slashes).
 *      Snapshots live under OPENCODE_SNAPSHOT_DIR, else the user cache dir,
 *      else the tmpdir. Threads from here are archive-view-only: the colony
 *      records the archive on its own side; writing a remote store file
 *      from here would race Desktop, which rewrites its records from memory.
 *
 *   2. `opencode serve` HTTP API (LIVE OVERLAY). Desktop binds loopback-only
 *      (127.0.0.1) on a RANDOM port with an AUTOGENERATED password — both
 *      rotate every Desktop launch — so the colony reaches it through a
 *      read-only SSH tunnel, never over the LAN:
 *      `scripts/opencode-tunnel.sh -- <command>` resolves the current port
 *      and credentials fresh on every run (read-only process-env query;
 *      Desktop is never disrupted) and exports OPENCODE_SERVE_URL (plus
 *      OPENCODE_SERVE_USERNAME / OPENCODE_SERVE_PASSWORD). For the live
 *      colony, `scripts/opencode-keeper.sh` (systemd unit template in
 *      scripts/systemd/) holds that tunnel open persistently and publishes
 *      the same three values to a 0600 creds file this adapter reads on
 *      every scan — explicit env always wins, a stale file reads as
 *      unconfigured. A static
 *      OPENCODE_SERVE_URL (or OPENCODE_SERVE_HOST / OPENCODE_SERVE_PORT,
 *      default port 4096) also works for a hand-run LAN-bound serve.
 *      Optional basic auth via OPENCODE_SERVE_USERNAME / OPENCODE_SERVE_PASSWORD.
 *      Endpoints used: GET /session, GET /session/status, GET /project,
 *      GET /session/:id/message?limit=N (previews only, capped per scan).
 *      Serve threads merge INTO the snapshot list by session id: serve fills
 *      in live running flags and any fields the snapshot lacks, and sessions
 *      the snapshot has not seen yet (too new to have pulled) appear
 *      serve-backed until the next snapshot refresh absorbs them.
 *
 *   3. Local session-store copy (UNION MEMBER). Same copy-then-query
 *      mechanics as before for a store on THIS machine: the copy refreshes
 *      only when the source mtime/size changes (mtime cache, per ground
 *      rules). Point at one with OPENCODE_DB_PATH — e.g. a file pulled from
 *      the WinPC by hand — or leave unset for this machine's default store.
 *      This is how the host's own sessions (if any) still show alongside
 *      the WinPC history.
 *
 * Archive flag is the store's own `session.time_archived` (null = active),
 * set with one atomic UPDATE after re-reading the row — the colony never
 * invents its own archive state. That write only ever touches a LOCAL store
 * file we resolved ourselves (never a snapshot copy, never a remote pull):
 * snapshot-backed threads are view-only for archiving, and the serve API
 * has no archive endpoint (only title PATCH), so serve-sourced threads are
 * view-only too.
 *
 * Opening: a thread opens iff it has a `share_url` — there is no Desktop deep
 * link to hand back, so unshared threads report why per the interface.
 *
 * Times in the store are epoch milliseconds (verified against a live db).
 */

